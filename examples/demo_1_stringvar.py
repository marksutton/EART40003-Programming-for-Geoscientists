# stringvar.py - use of string variables

# make string variables
hello_string = "hello"
world_string = "world"

# combine them with +
hello_world_string = hello_string + " cruel " + world_string

# print the combined string
print(hello_world_string)

# make two number variables
a = 10
b = 20

# put numbers into string using the 'f string' method
complex_string = f"Variable a is {a} and b is {b:.3f}"

# output string
print(complex_string)
